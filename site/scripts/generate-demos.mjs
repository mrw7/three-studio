// Regenerate the static gallery demos from the sandbox examples.
//
// The example scenes are plain function bodies for the preview sandbox: they
// use the globals THREE/scene/camera/renderer/controls/onFrame/setBackground/wb
// and never import anything. The gallery pages are ES modules, so this script
// recreates those globals at module scope, splices the example body in
// verbatim, and exports a `createStage(canvas)` factory. The product-content
// JSON (manual steps, film captions) is re-emitted as modules for the same
// reason: one source of truth under examples/, no hand-maintained copies.
//
// Run: node site/scripts/generate-demos.mjs
// Both the script and CI verify the output is byte-identical to what is
// committed (see tests/examples.test.mjs).
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..')

const SANDBOX_PRELUDE = `const renderer = new THREE.WebGLRenderer({ canvas, antialias: true, powerPreference: 'high-performance' })
renderer.setPixelRatio(Math.min(window.devicePixelRatio || 1, 1.75))
renderer.outputColorSpace = THREE.SRGBColorSpace
const scene = new THREE.Scene()
const camera = new THREE.PerspectiveCamera(35, canvas.clientWidth / Math.max(1, canvas.clientHeight), 0.1, 300)
const controls = new OrbitControls(camera, canvas)
controls.enableDamping = true
controls.dampingFactor = 0.075
const clock = { getElapsedTime: () => performance.now() / 1000 }
const frameCallbacks = []
const onFrame = callback => { frameCallbacks.push(callback) }
const setBackground = value => {
  scene.background = value instanceof THREE.Color ? value : new THREE.Color(value)
}
const wb = {
  id(object, name) {
    if (object !== null && object !== undefined && typeof object === 'object') {
      if (typeof name === 'string' && name.trim() !== '') {
        if (object.userData === undefined || object.userData === null) object.userData = {}
        object.userData.wbId = name.trim()
      }
    }
    return object
  },
}
const assets = {
  url: () => null, texture: () => null, model: () => null, hdri: () => null,
}
void clock
`

const RESIZE_AND_STAGE = `
const resize = () => {
  const width = canvas.clientWidth || window.innerWidth
  const height = canvas.clientHeight || window.innerHeight
  renderer.setSize(width, height, false)
  camera.aspect = width / Math.max(1, height)
  camera.updateProjectionMatrix()
}
resize()
window.addEventListener('resize', resize)

// The gallery pages drive the film/scene clock themselves, so the stage only
// renders a requested time. Example bodies read nothing else from the stage.
// OrbitControls.update() recomputes the camera from its own spherical state, so
// it must never run for a scene that animates the camera itself: the film
// example sets controls.enabled = false, and that is the signal used here.
const stage = {
  scene, camera, renderer, controls,
  byId(id) {
    let found = null
    scene.traverse(node => {
      if (found === null && node.userData && node.userData.wbId === id) found = node
    })
    return found
  },
  frame(time) {
    for (const callback of frameCallbacks) {
      callback({ time, delta: 1 / 60, elapsed: time, THREE, scene, camera, renderer, controls, canvas })
    }
    if (controls.enabled) controls.update()
    renderer.render(scene, camera)
  },
}
return stage
}
`

const scenes = [
  {
    example: 'examples/scene-engine.js',
    out: 'site/engine-demo/scene.js',
    banner: 'Turbofan stage, generated from examples/scene-engine.js.',
    camera: { near: 0.1, far: 220 },
  },
  {
    example: 'examples/scene-lamplighter.js',
    out: 'site/lamplighter-demo/scene.js',
    banner: 'The Lamplighter stage, generated from examples/scene-lamplighter.js.',
    camera: { near: 0.1, far: 300 },
  },
]

const write = async (relative, text) => {
  await mkdir(join(repo, dirname(relative)), { recursive: true })
  await writeFile(join(repo, relative), text, 'utf8')
  console.log('wrote ' + relative + ' (' + String(text.split('\n').length) + ' lines)')
}

for (const scene of scenes) {
  const body = await readFile(join(repo, scene.example), 'utf8')
  const prelude = SANDBOX_PRELUDE
    .replace('new THREE.PerspectiveCamera(35, canvas.clientWidth / Math.max(1, canvas.clientHeight), 0.1, 300)',
      'new THREE.PerspectiveCamera(35, canvas.clientWidth / Math.max(1, canvas.clientHeight), '
        + String(scene.camera.near) + ', ' + String(scene.camera.far) + ')')
  const header = '// ' + scene.banner + '\n'
    + '// Sandbox globals (THREE/scene/camera/renderer/controls/onFrame/wb/\n'
    + '// setBackground) are recreated here so the example body runs unchanged.\n'
    + '// Generated by site/scripts/generate-demos.mjs — do not edit by hand.\n'
    + "import * as THREE from 'three'\n"
    + "import { OrbitControls } from 'three/addons/OrbitControls.js'\n\n"
    + 'export function createStage(canvas) {\n'
  const output = header + prelude
    + '\n// ---- begin ' + scene.example + ' ----\n'
    + body
    + '\n// ---- end ' + scene.example + ' ----\n'
    + RESIZE_AND_STAGE
  await write(scene.out, output)
}

// Product content: the manual steps and the film captions, as modules.
