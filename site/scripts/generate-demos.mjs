const manualModule = '// Generated from examples/turbofan-manual.json by\n'
  + '// site/scripts/generate-demos.mjs — do not edit by hand.\n'
  + 'export const MANUAL = ' + JSON.stringify({
    title: manual.title,
    product: manual.product,
    version: manual.version,
    parts: manual.parts,
    steps: manual.steps.map(step => ({
      id: step.id,
      title: step.title,
      body: step.body,
      camera: step.camera,
      hidden: step.hidden,
      highlight: step.highlight,
      hotspots: step.hotspots,
    })),
  }, null, 2) + '\n'
await write('site/engine-demo/manual.js', manualModule)

